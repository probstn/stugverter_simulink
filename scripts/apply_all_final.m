%% 6. Speed from position (inside adc_to_sensor)
spd_sub = 'algorithm/adc_to_sensor/Speed from position';
spd_text = sprintf([...
'SPEED ESTIMATION: CIRCULAR UNWRAPPING & LOW-PASS FILTERING\n', ...
'==========================================================\n', ...
'1. WHAT IT DOES:\n', ...
'Calculates mechanical angular velocity (speed_rad_s) from rotor position samples,\n', ...
'unwrapping circular 2*pi phase boundaries, suppressing startup spikes, and filtering\n', ...
'quantization noise.\n\n', ...
'2. MATHEMATICAL FORMULAS:\n', ...
'Sample-to-sample angular difference:\n', ...
'  delta_theta = position_rad(k) - position_rad(k-1)\n\n', ...
'Circular shortest-path unwrapping (handles 0 <-> 2*pi transitions):\n', ...
'  delta_theta_unwrap = delta_theta - 2*pi * round(delta_theta / (2*pi))\n\n', ...
'Differentiated raw speed (with first-step startup suppression):\n', ...
'  omega_raw(1) = 0\n', ...
'  omega_raw(k) = delta_theta_unwrap / Ts          [Ts = 50 us (20 kHz)]\n\n', ...
'Discrete 1st-order Low-Pass Filter (cutoff fc = 150 Hz):\n', ...
'  omega_filt(k) = (1 - alpha) * omega_filt(k-1) + alpha * omega_raw(k)\n', ...
'  alpha = (2*pi * fc * Ts) / (1 + 2*pi * fc * Ts) ≈ 0.04505\n\n', ...
'3. WHY IT IS NEEDED:\n', ...
'- Boundary Wrap Immunity: As the rotor rotates past 2*pi -> 0 or 0 -> 2*pi, delta_theta\n', ...
'  would jump by +/-2*pi, producing an enormous false velocity spike (+/-125,663 rad/s).\n', ...
'  Shortest-path unwrapping eliminates this completely.\n', ...
'- Startup Quiescence: Suppressing the first step prevents false speed kicks when starting\n', ...
'  from a nonzero stationary angle.\n', ...
'- Noise Rejection: Differentiating quantized 12-bit ADC resolver signals amplifies high-\n', ...
'  frequency quantization noise; the 150 Hz LPF smooths the velocity signal for stable speed\n', ...
'  and current loop feedback.']);

set_param(spd_sub, 'Description', spd_text);
a = find_system(spd_sub, 'SearchDepth', 1, 'FindAll', 'on', 'Type', 'annotation');
