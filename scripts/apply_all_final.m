%% 2. FW Demag Floor
fw_sub = 'algorithm/current_control/FW Demag Floor';
fw_text = sprintf([...
'FIELD WEAKENING DEMAGNETIZATION FLOOR (PHYSICAL VOLTAGE ENVELOPE)\n', ...
'=================================================================\n', ...
'1. WHAT IT DOES:\n', ...
'Computes the maximum permissible stator flux linkage for the current rotor speed\n', ...
'given the inverter voltage headroom, calculates the minimum negative d-axis\n', ...
'demagnetization current required to stay within that flux limit, and enforces this\n', ...
'floor on id_ref.\n\n', ...
'2. MATHEMATICAL FORMULAS:\n', ...
'  omega_e      = P * |omega_m|\n', ...
'  omega_e_safe = max(omega_e, 100 rad/s)          [Zero-speed division guard]\n', ...
'  V_max        = V_phase_max = 0.92 * V_dc / sqrt(3) ≈ 318.7 V\n\n', ...
'Maximum allowable stator flux linkage before voltage saturation:\n', ...
'  lambda_max   = V_max / omega_e_safe\n\n', ...
'Required d-axis current to suppress stator flux to lambda_max:\n', ...
'  i_d_floor_raw = (lambda_max - lambda_pm) / L_d\n', ...
'  i_d_floor     = min(0, i_d_floor_raw)           [No positive FW magnetizing current]\n\n', ...
'Effective d-axis current reference output:\n', ...
'  id_ref_out   = min(id_ref_in, i_d_floor)        [Enforces minimum negative d-axis floor]\n\n', ...
'3. WHY IT IS NEEDED:\n', ...
'- Open-Circuit Back-EMF Overvoltage: Above base speed (N_base ≈ 9,500 RPM), the rotor\n', ...
'  PM flux generates a back-EMF (omega_e * lambda_pm) exceeding available phase voltage.\n', ...
'  At 18,000-20,000 RPM, back-EMF exceeds 450-500 V against a 318.7 V inverter limit.\n', ...
'- Inverter Saturation Prevention: If the speed/MTPA loop cannot request negative i_d\n', ...
'  fast enough during rapid acceleration, the inverter saturates, current regulation\n', ...
'  collapses, and catastrophic uncontrolled braking/regeneration occurs.\n', ...
'- Deterministic Safety Floor: FW Demag Floor acts as an instantaneous, feedforward\n', ...
'  physical constraint that guarantees stator terminal back-EMF remains feasible at all RPM.']);

