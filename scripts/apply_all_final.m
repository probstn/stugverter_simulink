%% 1. Feedforward Decoupling
ff_sub = 'algorithm/current_control/Feedforward Decoupling';
ff_text = sprintf([...
'FIELD-ORIENTED CONTROL: FEEDFORWARD VOLTAGE DECOUPLING\n', ...
'======================================================\n', ...
'1. WHAT IT DOES:\n', ...
'Computes and injects speed-dependent cross-coupling and rotor back-EMF feedforward\n', ...
'voltages (Vd_ff, Vq_ff) directly into the d- and q-axis voltage commands.\n\n', ...
'2. GOVERNING MOTOR EQUATIONS (Synchronous Rotor dq-Frame):\n', ...
'  v_d = R_s * i_d + L_d * (di_d/dt) - omega_e * L_q * i_q\n', ...
'  v_q = R_s * i_q + L_q * (di_q/dt) + omega_e * L_d * i_d + omega_e * lambda_pm\n\n', ...
'where:\n', ...
'  omega_e   = P * omega_m         [Electrical angular speed, rad/s]\n', ...
'  P         = 4                   [Pole pairs]\n', ...
'  L_d, L_q  = 0.35 mH, 0.55 mH    [Direct and quadrature axis inductances]\n', ...
'  lambda_pm = 0.0604 Wb           [Permanent magnet flux linkage]\n\n', ...
'3. FEEDFORWARD DECOUPLING FORMULAS:\n', ...
'  Vd_ff = - omega_e * L_q * i_q\n', ...
'  Vq_ff = + omega_e * (L_d * i_d + lambda_pm)\n\n', ...
'Voltage commands to inverter:\n', ...
'  v_d* = v_d_PI + Vd_ff\n', ...
'  v_q* = v_q_PI + Vq_ff\n\n', ...
'4. WHY IT IS NEEDED:\n', ...
'- Nonlinear Decoupling: In IPMSMs, d and q dynamics are strongly coupled through\n', ...
'  rotor velocity. Without feedforward, i_q transients disturb i_d and vice versa.\n', ...
'- High-Speed Back-EMF & Cross-Coupling Rejection: At maximum speed (20,000 RPM),\n', ...
'  omega_e reaches ~8,377 rad/s, producing back-EMF > 500 V and cross-coupling > 200 V.\n', ...
'  Without feedforward, the feedback PI integrators must synthesize these huge voltages\n', ...
'  purely through tracking error, resulting in severe phase lag, overshoot, and windup.\n', ...
'- Ideal Linear SISO Plant: Feedforward cancels the coupling voltages, reducing the\n', ...
'  plant seen by the PI controllers to two independent linear first-order SISO loops:\n', ...
'    v_d_PI ≈ R_s * i_d + L_d * (di_d/dt)\n', ...
'    v_q_PI ≈ R_s * i_q + L_q * (di_q/dt)\n', ...
'  ensuring uniform 800 Hz current loop bandwidth across the entire speed envelope.']);

